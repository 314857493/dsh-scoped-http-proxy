import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
const output = await build({
  entryPoints: ["src/client.js"],
  bundle: true,
  write: false,
  format: "cjs",
  platform: "browser",
  external: ["react", "@deepseek-ai/dsh-client-ui-primitives"],
  target: "es2022",
});
const content = `// Generated by npm run build; edit src/client.js instead.\nwindow.__ModuleLoader__.load({id:'dsh-scoped-http-proxy',factory:(require)=>{\nconst module={exports:{}}; const exports=module.exports;\n${output.outputFiles[0].text}\nreturn module.exports;\n}});\n`;
if (process.argv.includes("--check")) {
  if ((await readFile("lib/client.js", "utf8")) !== content)
    throw new Error("lib/client.js is stale; run npm run build");
} else await writeFile("lib/client.js", content);
